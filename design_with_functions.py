numbers: List[int] = [-5, 3, -2, 8, -1, 0, 10, -7]
words: List[str] = ["ออกแบบ", " ", "ด้วย", " ", "ฟังก์ชัน", " ", "สนุก", "มาก", "!"]


# =====================================================================
# 3) Mapping: ค่าสัมบูรณ์ของทุกสมาชิกใน `numbers`
# =====================================================================
def map_absolute(values: Iterable[int]) -> List[int]:
    """คืนลิสต์ใหม่ที่มีค่าสัมบูรณ์ของแต่ละตัวเลขใน ``values``
    โดยใช้ฟังก์ชัน ``map`` ในตัวของ Python

    พารามิเตอร์:
        values: อิเทอเรเบิลของจำนวนเต็ม (เช่น ลิสต์ ``numbers``)

    คืนค่า:
        ลิสต์ที่แต่ละสมาชิกเป็น ``abs(x)`` ของค่า ``x`` ที่สอดคล้องกัน
        ใน ``values``

    ตัวอย่าง:
        >>> map_absolute([-5, 3, -2, 0])
        [5, 3, 2, 0]
    """
    return list(map(abs, values))


absolute_numbers: List[int] = map_absolute(numbers)


# =====================================================================
# 4) Filtering: เก็บเฉพาะเลขบวกใน `numbers`
#    (ใช้ lambda เป็นฟังก์ชันช่วย/auxiliary function ตามที่โจทย์บังคับ)
# =====================================================================
def filter_positive(values: Iterable[int]) -> List[int]:
    """คืนลิสต์ใหม่ที่มีเฉพาะจำนวนบวกใน ``values``
    โดยใช้ฟังก์ชัน ``filter`` ในตัวของ Python

    ฟังก์ชันเงื่อนไข (predicate) ที่ส่งเข้าไปใน ``filter`` คือ
    lambda expression (``lambda x: x > 0``) ซึ่งเป็น auxiliary
    function ที่โจทย์ระบุให้ต้องใช้อย่างชัดเจน

    พารามิเตอร์:
        values: อิเทอเรเบิลของจำนวนเต็ม (เช่น ลิสต์ ``numbers``)

    คืนค่า:
        ลิสต์ของสมาชิกใน ``values`` ที่มีค่ามากกว่าศูนย์ เรียงลำดับ
        ตามลำดับเดิม

    ตัวอย่าง:
        >>> filter_positive([-5, 3, -2, 8, -1, 0, 10, -7])
        [3, 8, 10]
    """
    return list(filter(lambda x: x > 0, values))


positive_numbers: List[int] = filter_positive(numbers)


# =====================================================================
# 5) Reducing: รวมลิสต์ `words` ให้เหลือสตริงเดียว
# =====================================================================
def reduce_to_string(pieces: Iterable[str]) -> str:
    """รวมอิเทอเรเบิลของสตริงให้เป็นสตริงเดียว โดยใช้
    ``functools.reduce``

    แต่ละขั้นตอนจะนำผลลัพธ์ที่สะสมไว้มาต่อกับชิ้นถัดไป:
    ``((piece1 + piece2) + piece3) + ...`` ไปเรื่อยๆ จนเหลือสตริง
    เดียว

    พารามิเตอร์:
        pieces: อิเทอเรเบิลของสตริง (เช่น ลิสต์ ``words``)

    คืนค่า:
        สตริงเดียวที่ได้จากการต่อสมาชิกทุกตัวใน ``pieces``
        ตามลำดับ

    ตัวอย่าง:
        >>> reduce_to_string(["Hello", ", ", "world", "!"])
        'Hello, world!'
    """
    return reduce(lambda a, b: a + b, pieces)


combined_string: str = reduce_to_string(words)


