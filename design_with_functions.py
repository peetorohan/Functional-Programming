# 2) displayRange (ฟังก์ชันแบบ recursive ตามที่โจทย์กำหนด)
# =====================================================================
def displayRange(lower: int, upper: int, step: int = 1) -> None:
    """แสดงผลตัวเลขทุกตัวในช่วง ``[lower, upper]`` (รวมทั้งสองขอบเขต)
    แบบ recursive (เรียกตัวเอง) โดยเลื่อนทีละ ``step`` ในแต่ละการเรียก

    ต่างจากฟังก์ชันแบบลูป ฟังก์ชันนี้ยึดหลัก *recursive design recipe*:
        - Base case (เงื่อนไขหยุด): หยุดเมื่อไม่มีค่าเหลือให้แสดงแล้ว
        - Recursive case (กรณีเรียกซ้ำ): ทำงานกับค่าปัจจุบัน แล้ว
          ส่งต่อค่าที่เหลือให้การเรียกซ้ำครั้งถัดไปจัดการ

    พารามิเตอร์:
        lower: ค่าปัจจุบันที่จะแสดงผล ทำหน้าที่เหมือนตัวนับในลูป
            ตลอดการเรียกซ้ำ
        upper: ค่าสุดท้ายที่อนุญาตในช่วง - รวมค่านี้ด้วย
        step: ค่าที่เพิ่มเข้าไปใน ``lower`` ในแต่ละครั้งที่เรียกซ้ำ
            ค่าเริ่มต้นคือ ``1``

    คืนค่า:
        ไม่มี (None) ผลลัพธ์ของฟังก์ชันนี้คือการพิมพ์ออกหน้าจอ

    ตัวอย่าง:
        >>> displayRange(1, 5)
        1
        2
        3
        4
        5
    """
    # ---- Base case: ช่วงหมดแล้ว --------------------------------------
    if lower > upper:
        return

    # ---- ทำงานในการเรียกครั้งนี้ ---------------------------------------
    print(lower)

    # ---- Recursive case: จัดการค่าที่เหลือในช่วง ------------------------
    displayRange(lower + step, upper, step)


