# 1) summation
# =====================================================================
def summation(
    lower: int,
    upper: int,
    step: int = 1,
    func: Callable[[int], float] = lambda x: x,
) -> float:
    """หาผลรวมของ ``func(x)`` สำหรับทุกค่า ``x`` ในช่วง
    ``[lower, upper]`` (รวมทั้งสองขอบเขต) โดยเลื่อนทีละ ``step``

    นี่คือฟังก์ชัน summation แบบทั่วไป (generalised) ตามหลักการใน
    *Design with Functions*: แทนที่จะบวกเลขดิบๆ อย่างเดียว
    ฟังก์ชันนี้เปิดโอกาสให้ผู้เรียกใช้ (1) ข้ามค่าด้วย ``step`` และ
    (2) แปลงแต่ละค่าด้วย ``func`` ก่อนนำไปบวกสะสม

    พารามิเตอร์:
        lower: ค่าเริ่มต้น (น้อยที่สุด) ของช่วง - รวมค่านี้ด้วย
        upper: ค่าสุดท้าย (มากที่สุด) ของช่วง - รวมค่านี้ด้วย
        step: ระยะการเลื่อนไปยังค่าถัดไป
            ค่าเริ่มต้นคือ ``1`` (เดินผ่านทุกจำนวนเต็ม)
        func: ฟังก์ชันรับหนึ่งอาร์กิวเมนต์ที่จะถูกนำไปใช้กับแต่ละค่า
            ก่อนนำไปบวกสะสม ค่าเริ่มต้นคือฟังก์ชัน identity
            ``lambda x: x`` (บวกตัวเลขนั้นตรงๆ โดยไม่แปลงค่า)

    คืนค่า:
        ผลรวมสะสมของ ``func(x)`` ตลอดทั้งช่วง

    ตัวอย่าง:
        >>> summation(1, 100)                     # ผลรวมปกติ 1..100
        5050
        >>> summation(1, 10, 2)                   # 1 + 3 + 5 + 7 + 9
        25
        >>> round(summation(1, 100, 2, math.sqrt), 2)
        333.42
    """
    total = 0
    for value in range(lower, upper + 1, step):
        total += func(value)
    return total


